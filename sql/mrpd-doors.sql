-- ===========================================================================
--  Gabz MRPD doors for ox_doorlock  --  REMOVAL
--
--  THIS FILE NOW DELETES THE DOORS IT USED TO CREATE. Import it once:
--
--    mysql -u root -p stateofmindrp < sql/mrpd-doors.sql
--
--  ---------------------------------------------------------------------------
--  WHY THE IMPORT WAS WITHDRAWN
--
--  The 19 doors it added were converted from a public qb-doorlock config for a
--  DIFFERENT revision of Gabz MRPD. Most landed slightly off the real doors,
--  which was expected to fail harmlessly. It did not.
--
--  ox_doorlock registers every door with AddDoorToSystem(hash, model, x, y, z)
--  under its own generated hash. When two records describe the SAME physical
--  door, the game ends up with two door-system entries for one door, and
--  unlocking one leaves the other still holding it shut. /pddoors showed
--  exactly that: a hand-made door and an imported one, both 0.8m away, both
--  model -1406685646 (gabz_mrpd_door_04).
--
--  So the symptom was never "the imported doors do nothing". It was "the
--  imported doors break the doors that DID work", which is much worse, and it
--  is why the reception doors would not unlock while the main entrance would.
--
--  ---------------------------------------------------------------------------
--  WHAT THIS DELETES, AND WHAT IT KEEPS
--
--  Only names beginning with "MRPD " (with a space) go: that is exactly the set
--  the import created. Doors made by hand through /doorlock are named however
--  you named them, so "MRPD-1" and anything else you built survives.
--
--  Build the rest with /doorlock. It snaps to the door you are looking at, so
--  the coordinates are correct by construction, which is the one thing an
--  imported list cannot promise.
-- ===========================================================================

DELETE FROM `ox_doorlock` WHERE `name` LIKE 'MRPD %';
