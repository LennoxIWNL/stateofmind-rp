#!/usr/bin/env node
// Writes som-staff/shared/health_lists.lua: the resources, tables and items
// /somhealth must find on a booted server, taken from the repo itself.
//   node tools/gen-health-lists.mjs          rewrite the file
//   node tools/gen-health-lists.mjs --check  fail if it is out of date
// Made by Lennox.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const base = readdirSync(join(root, 'txData')).map((d) => join(root, 'txData', d)).find((d) => existsSync(join(d, 'resources')))
const som = join(base, 'resources', '[som]')

// Only resources som.cfg actually ensures count (som-traffic is deliberately off).
const ensured = new Set(readFileSync(join(base, 'som.cfg'), 'utf8').split('\n').map((l) => /^\s*ensure\s+([\w-]+)\s*$/.exec(l)).filter(Boolean).map((m) => m[1]))
const resources = readdirSync(som).filter((n) => statSync(join(som, n)).isDirectory() && existsSync(join(som, n, 'fxmanifest.lua')) && ensured.has(n)).sort()
const tables = [...readFileSync(join(root, 'setup.sql'), 'utf8').matchAll(/CREATE TABLE IF NOT EXISTS `(som_[a-z0-9_]+)`/g)].map((m) => m[1]).sort()

function* walk(dir) {
  for (const n of readdirSync(dir)) {
    if (n === 'node_modules' || n === 'html') continue
    const p = join(dir, n)
    if (statSync(p).isDirectory()) yield* walk(p)
    else if (n.endsWith('.lua') && !n.endsWith('fxmanifest.lua')) yield p
  }
}
const items = new Set()
for (const f of walk(som)) {
  const code = readFileSync(f, 'utf8')
  for (const m of code.matchAll(/(?:AddItem|RemoveItem)\(\s*[\w.]+\s*,\s*['"]([a-z0-9_]+)['"]/g)) items.add(m[1])
}
for (const m of readFileSync(join(root, 'ECONOMY-MAP.md'), 'utf8').matchAll(/^\| `([a-z0-9_]+)` \|/gm)) items.add(m[1])
const itemList = [...items].filter((n) => !/^weapon_/i.test(n)).sort()

const quote = (a) => a.map((x) => `    '${x}',`).join('\n')
const out = `-- Generated by tools/gen-health-lists.mjs. Do not edit by hand.
HealthLists = {
    resources = {
${quote(resources)}
    },
    tables = {
${quote(tables)}
    },
    items = {
${quote(itemList)}
    },
}
`
const file = join(som, 'som-staff', 'shared', 'health_lists.lua')
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== out) { console.error('health_lists.lua is stale: run node tools/gen-health-lists.mjs'); process.exit(1) }
  process.exit(0)
}
writeFileSync(file, out)
console.log(`${resources.length} resources, ${tables.length} tables, ${itemList.length} items`)
